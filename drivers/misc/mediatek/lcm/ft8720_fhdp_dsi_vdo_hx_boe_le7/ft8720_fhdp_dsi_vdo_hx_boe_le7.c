static int nt50358_write_byte(unsigned char cmd, unsigned char data)
{
    unsigned char buf[2] = {cmd, data};
    struct i2c_msg msg = {
        .addr = 0x3E,
        .flags = 0,
        .len = 2,
        .buf = buf,
    };
    struct i2c_adapter *adap;
    int ret = -1;
    int bus;

    adap = i2c_get_adapter(6);
    if (adap) {
        ret = i2c_transfer(adap, &msg, 1);
        i2c_put_adapter(adap);
        if (ret == 1) {
            pr_info("[LCM] NT50358 write (0x%02X=0x%02X) on i2c6 SUCCESS\n", cmd, data);
            return 0;
        }
    }

    for (bus = 0; bus <= 8; bus++) {
        if (bus == 6) continue;
        adap = i2c_get_adapter(bus);
        if (adap) {
            ret = i2c_transfer(adap, &msg, 1);
            i2c_put_adapter(adap);
            if (ret == 1) {
                pr_info("[LCM] NT50358 write (0x%02X=0x%02X) on i2c%d SUCCESS\n", cmd, data, bus);
                return 0;
            }
        }
    }
    pr_warn("[LCM] NT50358 write (0x%02X=0x%02X) failed on all buses\n", cmd, data);
    return ret;
}

static void lcm_init_power(void)
{
    pr_info("[LCM] %s: activating NT50358 (+5.5V/-5.5V) bias power\n", __func__);
    disp_dts_gpio_select_state(8); // lcd_bias_enp1_gpio (State 8: Positive Bias High)
    MDELAY(5);
    disp_dts_gpio_select_state(10); // lcd_bias_enn1_gpio (State 10: Negative Bias High)
    MDELAY(1);

    nt50358_write_byte(0x00, 0x0F); // VSP +5.5V
    MDELAY(1);
    nt50358_write_byte(0x01, 0x0F); // VSN -5.5V
    MDELAY(1);
    nt50358_write_byte(0x03, 0x33);
    MDELAY(1);
    nt50358_write_byte(0xFF, 0x80);
    MDELAY(5);
}

static void lcm_suspend_power(void)
{
    pr_info("[LCM] %s: suspend power\n", __func__);
    disp_dts_gpio_select_state(7); // lcd_bias_enp0_gpio (State 7: Positive Bias Low)
    disp_dts_gpio_select_state(9); // lcd_bias_enn0_gpio (State 9: Negative Bias Low)
    is_suspended = 1;
}

static void lcm_resume_power(void)
{
    pr_info("[LCM] %s: resume power\n", __func__);
    if (is_suspended == 1) {
        lcm_init_power();
        is_suspended = 0;
    }
}

static void lcm_init(void)
{
    lcm_init_power();
    pr_info("[LCM] %s: toggling reset and sending init sequence\n", __func__);
    MDELAY(5);
    disp_dts_gpio_select_state(4); // lcm_rst_out1_gpio (State 4: Reset High)
    MDELAY(5);
    disp_dts_gpio_select_state(3); // lcm_rst_out0_gpio (State 3: Reset Low)
    MDELAY(5);
    disp_dts_gpio_select_state(4); // lcm_rst_out1_gpio (State 4: Reset High)
    MDELAY(20);

    push_table(init_setting, sizeof(init_setting) / sizeof(struct LCM_setting_table), 1);
    pr_info("[LCM] %s: 197 commands pushed successfully\n", __func__);
}

static void lcm_suspend(void)
{
    dsi_set_cmdq_V2(0x28, 0, NULL, 1);
    MDELAY(20);
    dsi_set_cmdq_V2(0x10, 0, NULL, 1);
    MDELAY(120);
    lcm_suspend_power();
}

static void lcm_resume(void)
{
    lcm_init();
}

